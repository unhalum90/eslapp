"use client";

import React, { useState } from 'react';
import { FlashcardActivity } from '@/components/activities/FlashcardActivity';
import { DominoActivity } from '@/components/activities/DominoActivity';
import { BoardGameActivity } from '@/components/activities/BoardGameActivity';
import { FreeTimeActivity } from '@/components/activities/FreeTimeActivity';
import { SurveyActivity } from '@/components/activities/SurveyActivity';
import { SupplementaryActivity } from '@/components/activities/SupplementaryActivity';
import { generateActivities, GeneratedActivityPack } from '@/app/actions/generateActivities';
import { Sparkles, Loader2, Download, RefreshCw } from 'lucide-react';
import { jsPDF } from 'jspdf';

const TABS = [
    { label: 'Overview', icon: '📋' },
    { label: 'Flashcards', icon: '🗣️' },
    { label: 'Dominoes', icon: '🧩' },
    { label: 'Board Game', icon: '🏠' },
    { label: 'Categories', icon: '🍔' },
    { label: 'Snakes', icon: '🐍' },
    { label: 'Roll Grid', icon: '🎯' },
];

const LEVELS = ['A1', 'A2', 'B1', 'B2'];

export default function ActivitiesPage() {
    const [activeTab, setActiveTab] = useState<number>(0);
    const [topic, setTopic] = useState('');
    const [level, setLevel] = useState('A1-A2');
    const [isGenerating, setIsGenerating] = useState(false);
    const [generatedPack, setGeneratedPack] = useState<GeneratedActivityPack | null>(null);
    const [error, setError] = useState<string | null>(null);

    const handleGenerate = async () => {
        if (!topic.trim()) return;
        setIsGenerating(true);
        setError(null);

        try {
            const pack = await generateActivities(topic, level);
            setGeneratedPack(pack);
            setActiveTab(1); // Jump to first activity
        } catch (err) {
            setError('Failed to generate activities. Please try again.');
            console.error(err);
        } finally {
            setIsGenerating(false);
        }
    };

    const handleReset = () => {
        setGeneratedPack(null);
        setTopic('');
        setActiveTab(0);
    };

    const handleExportPDF = async () => {
        const pdf = new jsPDF({
            orientation: 'portrait',
            unit: 'mm',
            format: 'a4',
        });

        const title = generatedPack?.topic || 'ESL Activity Pack';
        const pageWidth = pdf.internal.pageSize.getWidth();

        // Cover page
        pdf.setFillColor(79, 70, 229); // Indigo
        pdf.rect(0, 0, pageWidth, 297, 'F');

        pdf.setTextColor(255, 255, 255);
        pdf.setFontSize(48);
        pdf.text('ESL Activity Pack', pageWidth / 2, 100, { align: 'center' });

        pdf.setFontSize(32);
        pdf.text(title.toUpperCase(), pageWidth / 2, 130, { align: 'center' });

        pdf.setFontSize(18);
        pdf.text(`Level: ${generatedPack?.level || 'A1-A2'}`, pageWidth / 2, 160, { align: 'center' });
        pdf.text(`${generatedPack?.vocabulary?.length || 48} Vocabulary Items`, pageWidth / 2, 175, { align: 'center' });

        pdf.setFontSize(14);
        pdf.text('6 Ready-to-Print Activities', pageWidth / 2, 200, { align: 'center' });
        pdf.text('• I Have, Who Has? Flashcards', pageWidth / 2, 215, { align: 'center' });
        pdf.text('• Word-Picture Dominoes', pageWidth / 2, 225, { align: 'center' });
        pdf.text('• Vocabulary Board Game', pageWidth / 2, 235, { align: 'center' });
        pdf.text('• Category Sorting Cards', pageWidth / 2, 245, { align: 'center' });
        pdf.text('• Snakes & Ladders Q&A', pageWidth / 2, 255, { align: 'center' });
        pdf.text('• Roll-a-Sentence Grammar Grid', pageWidth / 2, 265, { align: 'center' });

        pdf.setFontSize(12);
        pdf.text(`Generated by The ESL Architect`, pageWidth / 2, 285, { align: 'center' });

        pdf.save(`${title.replace(/\s+/g, '_')}_Activity_Pack.pdf`);
    };

    const renderContent = () => {
        switch (activeTab) {
            case 0:
                return (
                    <div className="space-y-10 animate-fadeIn">
                        {/* AI Generator Section */}
                        <div className="bg-gradient-to-br from-purple-600 via-indigo-600 to-blue-600 p-8 rounded-3xl shadow-2xl text-white">
                            <div className="flex items-center gap-3 mb-6">
                                <div className="p-3 bg-white/20 rounded-2xl backdrop-blur">
                                    <Sparkles size={28} />
                                </div>
                                <div>
                                    <h2 className="text-3xl font-black tracking-tight">AI Activity Generator</h2>
                                    <p className="text-purple-100 font-medium">Type any topic → Get 6 custom activities instantly</p>
                                </div>
                            </div>

                            <div className="flex flex-col md:flex-row gap-4">
                                <div className="flex-1 relative">
                                    <input
                                        type="text"
                                        value={topic}
                                        onChange={(e) => setTopic(e.target.value)}
                                        onKeyDown={(e) => e.key === 'Enter' && handleGenerate()}
                                        placeholder="Enter a topic: Weather, Sports, Food, Travel..."
                                        className="w-full px-6 py-4 rounded-2xl text-slate-900 text-lg font-medium placeholder:text-slate-400 focus:outline-none focus:ring-4 focus:ring-white/30"
                                        disabled={isGenerating}
                                    />
                                </div>
                                <select
                                    value={level}
                                    onChange={(e) => setLevel(e.target.value)}
                                    className="px-4 py-4 rounded-2xl text-slate-900 font-bold text-lg focus:outline-none focus:ring-4 focus:ring-white/30 cursor-pointer"
                                    disabled={isGenerating}
                                >
                                    {LEVELS.map(l => (
                                        <option key={l} value={l}>{l}</option>
                                    ))}
                                    <option value="A1-A2">A1-A2</option>
                                    <option value="B1-B2">B1-B2</option>
                                </select>
                                <button
                                    onClick={handleGenerate}
                                    disabled={isGenerating || !topic.trim()}
                                    className="px-8 py-4 bg-white text-indigo-600 rounded-2xl font-black text-lg hover:bg-indigo-50 transition-all disabled:opacity-50 disabled:cursor-not-allowed flex items-center gap-3 shadow-lg"
                                >
                                    {isGenerating ? (
                                        <>
                                            <Loader2 size={24} className="animate-spin" />
                                            Generating...
                                        </>
                                    ) : (
                                        <>
                                            <Sparkles size={24} />
                                            Generate!
                                        </>
                                    )}
                                </button>
                            </div>

                            {error && (
                                <div className="mt-4 p-4 bg-red-500/20 border border-red-300/30 rounded-xl text-red-100">
                                    {error}
                                </div>
                            )}

                            {generatedPack && (
                                <div className="mt-6 p-4 bg-white/20 backdrop-blur rounded-2xl flex flex-wrap items-center justify-between gap-4">
                                    <div>
                                        <p className="font-bold text-lg">✨ Generated: {generatedPack.topic}</p>
                                        <p className="text-purple-100">{generatedPack.vocabulary.length} vocabulary items • {generatedPack.gridPrompts.length} prompts</p>
                                    </div>
                                    <div className="flex gap-3">
                                        <button
                                            onClick={handleExportPDF}
                                            className="px-6 py-3 bg-emerald-500 hover:bg-emerald-600 rounded-xl font-bold flex items-center gap-2 transition-colors"
                                        >
                                            <Download size={20} />
                                            Export Lesson Pack
                                        </button>
                                        <button
                                            onClick={handleReset}
                                            className="px-6 py-3 bg-white/20 hover:bg-white/30 rounded-xl font-bold flex items-center gap-2 transition-colors"
                                        >
                                            <RefreshCw size={20} />
                                            Reset
                                        </button>
                                    </div>
                                </div>
                            )}
                        </div>

                        {/* Activity Overview Cards */}
                        <div className="bg-gradient-to-br from-indigo-100 to-blue-50 p-10 rounded-3xl border-2 border-indigo-200 shadow-sm">
                            <h2 className="text-4xl font-black text-indigo-950 mb-6 tracking-tight">
                                {generatedPack ? `${generatedPack.topic} Activities` : 'Lesson Summary'}
                            </h2>
                            <p className="text-xl text-indigo-800 leading-relaxed mb-10 font-medium">
                                {generatedPack
                                    ? `Custom-generated activities for "${generatedPack.topic}" at ${generatedPack.level} level with ${generatedPack.vocabulary.length} vocabulary items.`
                                    : 'This 60-minute lesson is designed for beginners. Generate a custom topic above or use the default activities!'}
                            </p>

                            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 xl:grid-cols-6 gap-6">
                                {TABS.slice(1).map((tab, idx) => (
                                    <button
                                        key={idx}
                                        onClick={() => setActiveTab(idx + 1)}
                                        className="bg-white p-6 rounded-2xl shadow-sm border border-indigo-100 hover:shadow-md hover:border-indigo-300 transition-all text-left group"
                                    >
                                        <span className="text-4xl mb-4 block">{tab.icon}</span>
                                        <h4 className="text-xl font-black text-slate-900 uppercase group-hover:text-indigo-600">{tab.label}</h4>
                                    </button>
                                ))}
                            </div>
                        </div>
                    </div>
                );
            case 1: return <FlashcardActivity customVocabulary={generatedPack?.vocabulary} />;
            case 2: return <DominoActivity customVocabulary={generatedPack?.vocabulary} />;
            case 3: return <BoardGameActivity customVocabulary={generatedPack?.vocabulary} />;
            case 4: return <FreeTimeActivity customVocabulary={generatedPack?.vocabulary} />;
            case 5: return <SurveyActivity customVocabulary={generatedPack?.vocabulary} />;
            case 6: return <SupplementaryActivity customGridPrompts={generatedPack?.gridPrompts} />;
            default: return null;
        }
    };

    return (
        <div className="max-w-7xl mx-auto">
            <div className="mb-10 overflow-x-auto pb-2 no-print">
                <div className="flex space-x-3 min-w-max">
                    {TABS.map((tab, idx) => (
                        <button
                            key={idx}
                            onClick={() => setActiveTab(idx)}
                            className={`flex items-center gap-3 px-8 py-4 rounded-2xl font-black text-lg transition-all ${activeTab === idx
                                    ? 'bg-indigo-600 text-white shadow-lg shadow-indigo-200 ring-4 ring-indigo-100'
                                    : 'text-slate-500 hover:bg-white hover:text-indigo-600 border border-transparent hover:border-indigo-100'
                                }`}
                        >
                            <span className="text-2xl">{tab.icon}</span>
                            <span className="whitespace-nowrap">{tab.label}</span>
                        </button>
                    ))}
                </div>
            </div>

            <div className="min-h-[500px]">
                {renderContent()}
            </div>

            <style dangerouslySetInnerHTML={{
                __html: `
        @keyframes fadeIn {
          from { opacity: 0; transform: translateY(15px); }
          to { opacity: 1; transform: translateY(0); }
        }
        .animate-fadeIn { animation: fadeIn 0.5s cubic-bezier(0.16, 1, 0.3, 1); }
        @media print { .no-print { display: none !important; } }
      `}} />
        </div>
    );
}
